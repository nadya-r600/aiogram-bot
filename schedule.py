DAYS_RU = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье"]

async def get_schedule_for_date(target_date):
    weekday = target_date.weekday()
    day_data = SCHEDULE.get(weekday, {})
    
    if "both" in day_data:
        subjects = list(day_data["both"])
    else:
        subjects = list(day_data.get("+", []))
        subjects.extend(day_data.get("-", []))

    overrides = await get_overrides_for_date(target_date.isoformat())
    return DAYS_RU[weekday], subjects, overrides